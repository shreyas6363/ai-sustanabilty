import { GoogleGenerativeAI } from "@google/generative-ai";
import { AdvisorContext, generateFallbackAdvice } from "./fallbackAdvisor";

export interface AIAdvisorResponse {
  answer: string;
  mode: "GEMINI_LIVE" | "RULE_BASED_FALLBACK";
  disclaimer: string;
}

export async function askSustainabilityAdvisor(
  question: string,
  context: AdvisorContext
): Promise<AIAdvisorResponse> {
  const apiKey = process.env.GEMINI_API_KEY?.trim();

  // If no API key configured, use deterministic rule-based advisor
  if (!apiKey) {
    const fallback = generateFallbackAdvice(question, context);
    return {
      answer: fallback.text,
      mode: "RULE_BASED_FALLBACK",
      disclaimer:
        "Deterministic Rule-Based Fallback active. (To enable generative reasoning, configure GEMINI_API_KEY in .env)",
    };
  }

  try {
    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({
      model: "gemini-1.5-flash",
      generationConfig: {
        temperature: 0.2, // Low temperature for high factual accuracy
        maxOutputTokens: 1000,
      },
    });

    const systemPrompt = `You are EcoPulse AI Advisor, an expert environmental and sustainability intelligence consultant for ${context.organizationName}.
You must answer questions strictly based on the following verified database facts.
DO NOT fabricate numbers, sensors, or hypothetical savings.
Clearly distinguish between historical facts, estimates, forecasts, and recommendations.
If data is insufficient to answer with certainty, say so clearly.

CURRENT REPORTING PERIOD: ${context.reportingPeriod}
VERIFIED CONSUMPTION METRICS:
- Total Water: ${context.totalWaterLitres.toLocaleString()} Litres
- Total Electricity: ${context.totalElectricityKwh.toLocaleString()} kWh
- Total Waste: ${context.totalWasteKg.toLocaleString()} kg (Recycled/Diverted: ${context.wasteRecycledPct.toFixed(1)}%)
- Carbon Footprint: ${context.totalCarbonKgCo2e.toLocaleString()} kg CO2e (Estimated via activity x factor)
- Overall Sustainability Score: ${context.sustainabilityScore.toFixed(1)}/100 (Grade: ${context.sustainabilityGrade})

BUILDING PERFORMANCE BREAKDOWN:
${context.buildingStats
  .map(
    (b) =>
      `- ${b.name} (${b.code}): Water=${b.waterLitres.toLocaleString()} L, Electricity=${b.electricityKwh.toLocaleString()} kWh, Waste=${b.wasteKg.toLocaleString()} kg${b.areaSqFt ? `, Area=${b.areaSqFt} sq.ft` : ""}${b.occupancy ? `, Occupancy=${b.occupancy}` : ""}`
  )
  .join("\n")}

ACTIVE FLAGGED ANOMALIES:
${
  context.activeAnomalies.length > 0
    ? context.activeAnomalies
        .map(
          (a) =>
            `- ${a.buildingName} [${a.resourceType} - ${a.severity}]: +${a.deviationPct}% deviation. ${a.explanation}`
        )
        .join("\n")
    : "None currently flagged."
}

ACTIVE RECOMMENDATIONS:
${
  context.topRecommendations.length > 0
    ? context.topRecommendations
        .map(
          (r) =>
            `- [${r.priority}] ${r.title} (${r.category}): Evidence="${r.evidence}"`
        )
        .join("\n")
    : "None active."
}
`;

    const result = await model.generateContent([
      { text: systemPrompt },
      { text: `User Question: ${question}` },
    ]);

    const answer = result.response.text();
    return {
      answer,
      mode: "GEMINI_LIVE",
      disclaimer: "Generated by Google Gemini AI using live organization context.",
    };
  } catch (err) {
    console.warn("Gemini API call failed, activating rule-based fallback:", err);
    const fallback = generateFallbackAdvice(question, context);
    return {
      answer: fallback.text,
      mode: "RULE_BASED_FALLBACK",
      disclaimer:
        "Rule-Based Fallback active (Gemini API service temporarily unavailable or key invalid).",
    };
  }
}

/**
 * Classifies an uploaded waste image into standard categories
 */
export async function classifyWasteImage(
  base64Image: string,
  mimeType = "image/jpeg"
): Promise<{
  suggestedCategory: string;
  confidencePct: number;
  notes: string;
  isAiClassified: boolean;
}> {
  const apiKey = process.env.GEMINI_API_KEY?.trim();

  if (!apiKey) {
    return {
      suggestedCategory: "RESIDUAL",
      confidencePct: 50,
      notes:
        "Manual classification required. (AI image vision is disabled because GEMINI_API_KEY is not configured).",
      isAiClassified: false,
    };
  }

  try {
    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({ model: "gemini-1.5-flash" });

    const prompt = `Analyze this image of waste/discarded material.
Identify the primary waste category from ONLY these valid options:
ORGANIC, PAPER, PLASTIC, GLASS, METAL, E_WASTE, RESIDUAL, OTHER.

Return a valid JSON object matching this structure:
{
  "category": "PLASTIC",
  "confidencePct": 85,
  "explanation": "Appears to be a PET beverage container with screw cap."
}`;

    const imagePart = {
      inlineData: {
        data: base64Image.replace(/^data:image\/\w+;base64,/, ""),
        mimeType,
      },
    };

    const response = await model.generateContent([prompt, imagePart]);
    const text = response.response.text();
    
    // Parse JSON from response
    const jsonMatch = text.match(/\{[\s\S]*\}/);
    if (jsonMatch) {
      const parsed = JSON.parse(jsonMatch[0]);
      return {
        suggestedCategory: parsed.category || "RESIDUAL",
        confidencePct: parsed.confidencePct || 70,
        notes: parsed.explanation || "Classified via Gemini Vision.",
        isAiClassified: true,
      };
    }

    return {
      suggestedCategory: "RESIDUAL",
      confidencePct: 60,
      notes: "AI classification returned unformatted response. Please verify manually.",
      isAiClassified: true,
    };
  } catch (err) {
    console.warn("Gemini vision classification failed:", err);
    return {
      suggestedCategory: "RESIDUAL",
      confidencePct: 50,
      notes: "Vision analysis unavailable. Please manually confirm category.",
      isAiClassified: false,
    };
  }
}
